#!/usr/bin/env python3
"""Validate both catalogs and generate small native/Bash tables (build time only)."""
import argparse
import json
from pathlib import Path
import re
import shlex

ROOT=Path(__file__).resolve().parents[2]
def unique(pairs):
    result={}
    for key,value in pairs:
        if key in result: raise ValueError('Duplicate message ID: '+key)
        result[key]=value
    return result

def catalogs():
    values={name:json.loads((ROOT/'i18n'/f'{name}.json').read_text(),object_pairs_hook=unique)
            for name in ('en-US','pt-BR')}
    en,pt=values.values()
    if set(en)!=set(pt):raise ValueError('Locale key coverage differs')
    pattern=r'\{\d+\}|%(?:\([A-Za-z_][A-Za-z0-9_]*\))?[0-9.+-]*[rsduliuf%]'
    for key in en:
        if not re.fullmatch(r'[a-z][a-z0-9_.]+',key):raise ValueError('Invalid message ID: '+key)
        if not all(isinstance(x[key],str) and x[key].strip() for x in values.values()):
            raise ValueError('Blank message: '+key)
        if re.findall(pattern,en[key])!=re.findall(pattern,pt[key]):
            raise ValueError('Placeholder mismatch: '+key)
        for catalog in values.values():
            if re.search(r'%(?!(?:\([A-Za-z_][A-Za-z0-9_]*\))?[0-9.+-]*[rsduliuf%])',catalog[key]):
                raise ValueError('Unsafe format specifier: '+key)
    known=set(en)
    for directory,pattern in (('src',r'prc_(?:tr|x11_label)\("([a-z0-9_.]+)"\)'),
                              ('scripts',r"\btr\(['\"]([a-z0-9_.]+)['\"]")):
        for path in (ROOT/directory).rglob('*'):
            if path.suffix not in ('.cpp','.hpp','.py'):continue
            for key in re.findall(pattern,path.read_text()):
                if key not in known:raise ValueError('Unknown source message: '+key)
    return values

def generated(values):
    en,pt=values['en-US'],values['pt-BR']
    keys=sorted(k for k in en if k.startswith(('native.','overlay.','common.')))
    cpp='// Generated by scripts/build/locales.py. Edit i18n/*.json.\n#pragma once\n'
    cpp+='struct PrcMessage { const char* id; const char* en; const char* pt; };\n'
    cpp+='inline constexpr PrcMessage kPrcMessages[] = {\n'
    for key in keys:
        cpp+='    {'+', '.join(json.dumps(x,ensure_ascii=False) for x in (key,en[key],pt[key]))+'},\n'
    cpp+='};\n'
    shell='# Generated by scripts/build/locales.py. Translation data are quoted, never evaluated.\n'
    for name,language in (('EN','en-US'),('PT','pt-BR')):
        shell+='declare -A PRC_MESSAGES_'+name+'=(\n'
        for key in sorted(en):
            if key.startswith(('shell.','language.','common.','lifecycle.','diagnostic.')):
                shell+='  ['+key+']='+shlex.quote(values[language][key])+'\n'
        shell+=')\n'
    return {ROOT/'src/i18n/generated.hpp':cpp,ROOT/'scripts/messages.bash':shell}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    values=catalogs()
    for path,content in generated(values).items():
        if args.check:
            if not path.is_file() or path.read_text()!=content:raise ValueError('Generated locale table is stale: '+str(path))
        else:path.write_text(content)
    print(f'PASS: {len(values["en-US"])} complete messages in en-US and pt-BR')

if __name__=='__main__':main()
